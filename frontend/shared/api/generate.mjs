// Regenerates shared/api/schema.d.ts from the backend's OpenAPI document.
// The document is read from the running dev api container (app.openapi()), so the
// types always match the backend in this checkout. Run from frontend/: pnpm gen:api
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");

const json = execFileSync(
  "docker",
  [
    "compose",
    "--env-file",
    resolve(root, "deploy/.env.dev"),
    "-f",
    resolve(root, "deploy/compose.dev.yaml"),
    "exec",
    "-T",
    "api",
    "python",
    "-c",
    "import json; from app.main import app; print(json.dumps(app.openapi()))",
  ],
  { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
);

const ast = await openapiTS(JSON.parse(json));
const header =
  "// Generated by shared/api/generate.mjs from the backend's OpenAPI. Do not edit.\n\n";
writeFileSync(resolve(here, "schema.d.ts"), header + astToString(ast));
console.log("wrote shared/api/schema.d.ts");
